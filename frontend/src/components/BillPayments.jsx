import { useState } from 'react';
import { billAPI, getErrorMessage } from '../api/client';
import { useAuth } from '../context/AuthContext';
import { todayISO } from '../utils/dates';
import { PAY_LABEL, PAY_TONE, fmtDate } from '../utils/format';
import { Chip } from './ui';

const MODES = [['bank', 'Bank transfer'], ['upi', 'UPI'], ['cheque', 'Cheque'], ['cash', 'Cash'], ['other', 'Other']];
const rs = (n) => `₹${Number(n || 0).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

/** Approval state + payments to the grower. Admins approve, record and remove payments. */
export default function BillPayments({ bill, onChange }) {
  const { isAdmin } = useAuth();
  const [form, setForm] = useState(null);
  const [error, setError] = useState('');
  const [busy, setBusy] = useState(false);
  const flockId = bill.flock;

  const act = async (fn) => {
    setBusy(true); setError('');
    try { const r = await fn(); onChange(r.data); setForm(null); }
    catch (err) {
      const d = err.response?.data;
      setError(d && typeof d === 'object' && !d.error ? Object.values(d).flat().join(' ') : getErrorMessage(err));
    }
    setBusy(false);
  };

  const pending = bill.approval_status !== 'approved';
  const due = Number(bill.balance_due);
  return (
    <section className="panel bill-pay" aria-label="Approval and payments">
      <div className="panel-head">
        <h2>Approval &amp; payments</h2>
        <div className="panel-actions">
          {pending ? <Chip tone="warn">Waiting for approval</Chip>
            : <Chip tone="ok">Approved{bill.approved_by_name ? ` by ${bill.approved_by_name}` : ''}{bill.approved_at ? ` · ${fmtDate(bill.approved_at)}` : ''}</Chip>}
          {!pending && <Chip tone={PAY_TONE[bill.payment_status]}>{PAY_LABEL[bill.payment_status]}</Chip>}
        </div>
      </div>
      <div className="panel-body">
        {pending && (
          <div className="pay-pending">
            <p>Generated by {bill.generated_by_name || 'a supervisor'}. An admin checks and approves the bill before any payment is made.</p>
            {isAdmin && <button className="btn btn-primary bill-no-print" disabled={busy} onClick={() => act(() => billAPI.approve(flockId))}>Approve bill</button>}
          </div>
        )}
        {!pending && (
          <>
            <dl className="kv pay-sum">
              <dt>To pay (after TDS)</dt><dd className="num">{rs(bill.amount_paid)}</dd>
              <dt>Paid</dt><dd className="num">{rs(bill.paid_total)}</dd>
              <dt>Balance due</dt><dd className={`num ${due > 0 ? 'tone-warn' : 'tone-ok'}`}>{rs(bill.balance_due)}</dd>
            </dl>
            {bill.payments.length > 0 && (
              <div className="table-wrapper">
                <table className="data-table cards-on-phone">
                  <thead><tr><th>Date</th><th className="r">Amount</th><th>Mode</th><th>Reference</th><th>Recorded by</th>{isAdmin && <th className="bill-no-print"></th>}</tr></thead>
                  <tbody>
                    {bill.payments.map(p => (
                      <tr key={p.id}>
                        <td className="cell-main">{fmtDate(p.date)}</td>
                        <td data-label="Amount" className="r num">{rs(p.amount)}</td>
                        <td data-label="Mode">{p.mode_label}</td>
                        <td data-label="Reference">{p.reference || '—'}{p.notes ? <span className="cell-sub">{p.notes}</span> : null}</td>
                        <td data-label="Recorded by">{p.recorded_by_name}{p.bill_version !== bill.version && <span className="cell-sub">on bill v{p.bill_version}</span>}</td>
                        {isAdmin && <td className="bill-no-print"><button className="btn-action btn-action-cancel" disabled={busy}
                          onClick={() => act(() => billAPI.deletePayment(p.id))} aria-label={`Remove payment of ${rs(p.amount)}`}>Remove</button></td>}
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )}
            {isAdmin && due > 0 && !form && (
              <button className="btn btn-primary bill-no-print" onClick={() => setForm({ date: todayISO(), amount: String(due), mode: 'bank', reference: '', notes: '' })}>
                + Record payment</button>
            )}
            {form && (
              <form className="pay-form bill-no-print" aria-label="Record payment"
                    onSubmit={e => { e.preventDefault(); act(() => billAPI.addPayment(flockId, form)); }}>
                <div className="rate-grid">
                  <div className="form-group"><label htmlFor="pay-date">Date *</label>
                    <input id="pay-date" type="date" required value={form.date} onChange={e => setForm({ ...form, date: e.target.value })} /></div>
                  <div className="form-group"><label htmlFor="pay-amount">Amount (₹) *</label>
                    <input id="pay-amount" type="number" step="0.01" min="0.01" required value={form.amount} onChange={e => setForm({ ...form, amount: e.target.value })} /></div>
                  <div className="form-group"><label htmlFor="pay-mode">Mode</label>
                    <select id="pay-mode" value={form.mode} onChange={e => setForm({ ...form, mode: e.target.value })}>
                      {MODES.map(([k, l]) => <option key={k} value={k}>{l}</option>)}</select></div>
                  <div className="form-group"><label htmlFor="pay-ref">UTR / reference</label>
                    <input id="pay-ref" value={form.reference} onChange={e => setForm({ ...form, reference: e.target.value })} /></div>
                </div>
                <div className="form-actions">
                  <button type="submit" className="btn btn-primary" disabled={busy}>Save payment</button>
                  <button type="button" className="btn btn-secondary" onClick={() => setForm(null)}>Cancel</button>
                </div>
              </form>
            )}
          </>
        )}
        {error && <p className="error-msg" role="alert">{error}</p>}
      </div>
    </section>
  );
}
